#!/usr/bin/env node
// R&D compiler: SVG path elements -> deterministic JS path payload.
// Source SVG is a design-time file only. The rendered film loads only the generated JS.
'use strict';
const fs=require('fs'),path=require('path');
const src=process.argv[2],out=process.argv[3];
if(!src||!out){console.error('usage: node tools/compile-vector-assets.cjs input.svg output.js');process.exit(2);}
const xml=fs.readFileSync(src,'utf8');
const paths={};
const re=/<path\b[^>]*\bid=["']([^"']+)["'][^>]*\bd=["']([^"']+)["'][^>]*>/gi;
let m;while((m=re.exec(xml)))paths[m[1]]=m[2];
if(!Object.keys(paths).length){console.error('no named path elements found');process.exit(1);}
const js=`// generated by compile-vector-assets.cjs\n(function(){'use strict';const data=${JSON.stringify(paths,null,2)};Object.defineProperty(FILM,'compiledVectorPayload',{value:Object.freeze(data),writable:false});})();\n`;
fs.mkdirSync(path.dirname(out),{recursive:true});fs.writeFileSync(out,js);
console.log(`compiled ${Object.keys(paths).length} paths -> ${out}`);
